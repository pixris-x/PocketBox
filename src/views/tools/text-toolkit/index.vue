<script setup>
// 合并页容器：UiTabs 切换子面板，当前 Tab 同步到 URL query（可分享 / 刷新保留 / 承接旧链接重定向）
import { computed, ref, watch } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import ToolShell from '@/components/ToolShell/index.vue'
import ToolkitPanel from './components/ToolkitPanel/index.vue'
import WhitespacePanel from './components/WhitespacePanel/index.vue'

const TABS = [
  { label: '批处理', value: 'toolkit' },
  { label: '空白清理', value: 'whitespace' },
]

const PANELS = {
  toolkit: ToolkitPanel,
  whitespace: WhitespacePanel,
}

const DEFAULT_TAB = 'toolkit'

const route = useRoute()
const router = useRouter()

function pickTab(value) {
  const tab = typeof value === 'string' ? value : ''
  return tab in PANELS ? tab : DEFAULT_TAB
}

const active = ref(pickTab(route.query.tab))
const panel = computed(() => PANELS[active.value])

// 地址栏直接改 ?tab= 或从旧路径重定向过来时同步状态
watch(
  () => route.query.tab,
  (value) => {
    active.value = pickTab(value)
  }
)

function onChange(value) {
  // replace 而非 push：切 Tab 不该产生大量历史记录
  router.replace({ query: { ...route.query, tab: value } })
}
</script>

<template>
  <ToolShell
    title="文本批处理"
    description="粘贴一段文本，一次完成去重、排序、大小写转换、空白清理与字数统计。全部在本地完成。"
  >
    <UiCard>
      <UiSection title="功能">
        <UiTabs v-model="active" :tabs="TABS" @update:model-value="onChange" />
      </UiSection>
    </UiCard>

    <component :is="panel" />
  </ToolShell>
</template>

